<?php

namespace MxBackup\Core\Contract;

/**
 * Удалённое хранилище архивов.
 *
 * Копия, лежащая на той же машине, что и сайт, защищает от испорченной базы и
 * неудачного деплоя, но не от потери самой машины. Отсюда выгрузка — часть
 * прогона, а не внешний скрипт: иначе она рано или поздно разъедется с
 * ротацией, и в облаке останется то, чего локально уже нет, либо наоборот.
 *
 * Интерфейс намеренно узкий: положить, забрать, перечислить, удалить. Всё, что
 * нужно для «снять копию — сохранить — восстановить — почистить старьё».
 */
interface RemoteStorageInterface
{
    /**
     * Человекочитаемое описание хранилища — идёт в отчёт и в письмо.
     * Например `s3://bucket/prefix/`.
     */
    public function describe();

    /**
     * Выгрузить архив.
     *
     * @param string                $path     Локальный файл.
     * @param string                $name     Имя архива (оно же хвост ключа).
     * @param array<string, string> $metadata Метки объекта: сумма, профиль, версия.
     * @return string Полный адрес объекта в хранилище.
     */
    public function upload($path, $name, array $metadata = []);

    /**
     * Скачать архив в локальный файл.
     *
     * @return string Путь к скачанному файлу.
     */
    public function download($name, $target);

    /**
     * Архивы в хранилище, новые первыми.
     *
     * @return array<int, array{name: string, size: int, modified: int}>
     */
    public function listArchives();

    /**
     * Удалить архив. Отсутствие объекта ошибкой не считается.
     */
    public function delete($name);
}
